"""Pack painted residential variants without changing their architecture.
All six fit one 2x2 residential plot. Volumes, roof height and yards vary.
Chimney mouths are measured in the untouched source bitmap coordinates.
"""
from pathlib import Path
from PIL import Image, ImageDraw
from isometric_art import painted_sprite, construction

MOD=Path(__file__).resolve().parents[1]
COUNT=6
FRAME=(184,184)
ANCHOR=(92,140)
VARIANTS=[
    # source, target bounding box, ground bottom, chimney mouth in source pixels
    ('cottage',(84,90),155,(550,137)),
    ('townhouse',(82,146),164,(386,152)),
    ('longhouse',(122,115),164,(410,104)),
    ('courtyard',(108,112),164,(654,140)),
    ('balcony',(106,130),164,(467,65)),
]
NAMES=['Maison du bourg','Petite chaumière','Maison à trois niveaux','Grande maison','Maison avec jardin','Maison à balcon']

def frames_and_metadata():
    frames=[painted_sprite('house',FRAME)]
    metadata=[dict(name=NAMES[0],chimney=(-1,-58),height=52)]
    for i,(name,size,bottom,mouth) in enumerate(VARIANTS,1):
        source=Image.open(MOD/'art-source'/f'house-{name}.png').convert('RGBA')
        # Ignore negligible transparent edge noise only when measuring the crop.
        # Alpha pixels inside the crop are preserved, including antialiasing.
        bounds=source.getchannel('A').point(lambda a:255 if a>12 else 0).getbbox()
        crop=source.crop(bounds)
        crop.thumbnail(size,Image.Resampling.LANCZOS)
        pos=(ANCHOR[0]-crop.width//2,bottom-crop.height)
        frame=Image.new('RGBA',FRAME);frame.alpha_composite(crop,pos)
        chimney=(round(pos[0]+(mouth[0]-bounds[0])*crop.width/(bounds[2]-bounds[0])-ANCHOR[0]),
                 round(pos[1]+(mouth[1]-bounds[1])*crop.height/(bounds[3]-bounds[1])-ANCHOR[1]))
        frames.append(frame)
        metadata.append(dict(name=NAMES[i],source=f'house-{name}.png',chimney=chimney,height=ANCHOR[1]-pos[1]-12))
    frames.append(construction('house'))
    return frames,metadata

def rules(metadata):
    lines=['# Generated by tools/house_art.py: offsets share the packed sprite anchor.',
           'md.house:','\tMedievalHouseLights:','\tMedievalHouseAppearance:',
           '\t\tChimneyX: '+', '.join(str(m['chimney'][0]) for m in metadata),
           '\t\tChimneyY: '+', '.join(str(m['chimney'][1]) for m in metadata),
           '\t\tSelectionHeights: '+', '.join(str(m['height']) for m in metadata),
           '\t-WithSpriteBody:','\tWithMedievalHouseBody:','\t\tRequiresCondition: built',
           '\t-IsometricSelectable:','\tMedievalHouseSelectable:','']
    return '\n'.join(lines)

def contact_sheet(frames,metadata):
    im=Image.new('RGB',(720,460),'#59684a');d=ImageDraw.Draw(im)
    for i,(frame,m) in enumerate(zip(frames,metadata)):
        x=(i%3)*240+28;y=(i//3)*225+12
        im.paste(frame,(x,y),frame)
        d.text((x,y+192),m['name'],fill='#f6e9ce')
    return im
